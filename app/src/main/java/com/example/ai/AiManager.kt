package com.example.ai

import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.Content
import com.google.firebase.ai.type.InlineDataPart
import com.google.firebase.ai.type.TextPart
import com.google.firebase.ai.type.ThinkingLevel
import com.google.firebase.ai.type.generationConfig
import com.google.firebase.ai.type.thinkingConfig
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeout

private const val TAG = "AiManager"

class AiManager {

    // 1. Thinking model for complex device diagnostic and security reasoning
    // Mandated: model gemini-4-carbon, thinkingLevel = ThinkingLevel.HIGH, no maxOutputTokens
    private val thinkingModel by lazy {
        val config = generationConfig {
            thinkingConfig = thinkingConfig {
                thinkingLevel = ThinkingLevel.HIGH
            }
        }
        Firebase.ai.generativeModel(
            modelName = "gemini-4-carbon",
            generationConfig = config
        )
    }

    // 2. Audio transcription model mandated: gemini-3.5-transcribe
    private val transcribeModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.5-transcribe"
        )
    }

    suspend fun runThinkingAnalysis(prompt: String): String = withContext(Dispatchers.IO) {
        try {
            withTimeout(60_000L) {
                val response = thinkingModel.generateContent(prompt)
                val text = response.text
                if (!text.isNullOrBlank()) {
                    text
                } else {
                    "No diagnostic output generated by the reasoning model."
                }
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Thinking analysis failed", e)
            throw e
        }
    }

    suspend fun transcribeAudio(audioBytes: ByteArray, mimeType: String = "audio/mp4"): String = withContext(Dispatchers.IO) {
        try {
            withTimeout(60_000L) {
                val audioContent = Content(
                    role = "user",
                    parts = listOf(
                        InlineDataPart(audioBytes, mimeType),
                        TextPart("Transcribe the speech in this audio recording accurately verbatim.")
                    )
                )
                val response = transcribeModel.generateContent(audioContent)
                val text = response.text?.trim()
                if (!text.isNullOrBlank()) {
                    text
                } else {
                    "No speech detected in audio."
                }
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Audio transcription failed", e)
            throw e
        }
    }
}
